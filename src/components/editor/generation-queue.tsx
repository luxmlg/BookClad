"use client";

import { useState, useEffect } from "react";
import { Loader2, Sparkles } from "lucide-react";
import { Badge } from "@/components/ui/badge";
import { Progress } from "@/components/ui/progress";
import { useGenerationPoller, type GenerationPollerState } from "./generation-poller";
import type { Generation } from "./types";
import { PANEL_MAX_HEIGHT } from "./types";
import {
  JOB_TYPE_ICON,
  getModelLabel,
  formatRelativeTime,
} from "./generation-history";
import { asAttributeSnapshot } from "./types";
import { formatAttributes } from "@/lib/attributes";

interface GenerationQueueProps {
  generations: Generation[];
  onComplete: (generationId: string, status: "COMPLETED" | "FAILED") => void;
}

export function GenerationQueue({
  generations,
  onComplete,
}: GenerationQueueProps) {
  // Tick counter to keep relative times fresh
  const [, setTick] = useState(0);
  useEffect(() => {
    if (generations.length === 0) return;
    const timer = setInterval(() => setTick((t) => t + 1), 30000);
    return () => clearInterval(timer);
  }, [generations.length]);

  if (generations.length === 0) {
    return (
      <div className="flex items-center justify-center gap-2 px-4 py-6 text-sm text-muted-foreground">
        No active generations
      </div>
    );
  }

  return (
    <div className="overflow-y-auto px-4 pb-3" style={{ maxHeight: PANEL_MAX_HEIGHT }}>
      <div className="space-y-2">
        {generations.map((gen) => (
          <QueueEntry
            key={gen.id}
            generation={gen}
            onComplete={onComplete}
          />
        ))}
      </div>
    </div>
  );
}

function QueueEntry({
  generation,
  onComplete,
}: {
  generation: Generation;
  onComplete: (generationId: string, status: "COMPLETED" | "FAILED") => void;
}) {
  const poller = useGenerationPoller({
    generationId: generation.id,
    onComplete,
  });

  const date =
    typeof generation.createdAt === "string"
      ? new Date(generation.createdAt)
      : generation.createdAt;
  const timeStr = formatRelativeTime(date);

  const jobType = generation.jobType ?? "generate";
  const Icon = JOB_TYPE_ICON[jobType] ?? Sparkles;
  const modelLabel = getModelLabel(generation.model);
  const attrs = asAttributeSnapshot(generation.attributeSnapshot);
  const imageCount = generation.imageCount ?? generation.images.length;

  const isActive = poller.status === "QUEUED" || poller.status === "PROCESSING";

  return (
    <div className="rounded-lg border bg-muted/30 px-3 py-2.5 space-y-2">
      {/* Header row */}
      <div className="flex items-center gap-2 text-sm">
        <Icon className="size-3.5 text-muted-foreground shrink-0" />
        {imageCount > 0 && (
          <span className="text-xs text-muted-foreground">
            {imageCount} {imageCount === 1 ? "image" : "images"}
          </span>
        )}
        <span
          className="ml-auto text-xs text-muted-foreground"
          title={date.toLocaleString()}
        >
          {timeStr}
        </span>
        {modelLabel && (
          <Badge variant="secondary" className="text-[10px] px-1.5 py-0">
            {modelLabel}
          </Badge>
        )}
        {isActive && (
          <Loader2 className="size-3.5 text-muted-foreground animate-spin shrink-0" />
        )}
      </div>

      {/* Details */}
      <div className="space-y-1 text-xs">
        {generation.prompt ? (
          <div>
            <span className="font-medium text-muted-foreground">
              {jobType === "inpaint" ? "Edit prompt: " : "Prompt: "}
            </span>
            <span className="line-clamp-2">{generation.prompt}</span>
          </div>
        ) : generation.jobType ? (
          <div className="text-muted-foreground italic">
            Prompt generated by AI
          </div>
        ) : null}

        {attrs && (
          <div className="text-muted-foreground">{formatAttributes(attrs)}</div>
        )}
      </div>

      {/* Progress */}
      <QueueProgress poller={poller} />
    </div>
  );
}

function QueueProgress({ poller }: { poller: GenerationPollerState }) {
  if (poller.status === "QUEUED") {
    return (
      <div className="flex items-center gap-2">
        <div className="h-3 w-3 shrink-0 animate-spin rounded-full border-2 border-primary border-t-transparent" />
        <span className="text-xs text-muted-foreground">Waiting in queue...</span>
      </div>
    );
  }

  if (poller.status === "PROCESSING") {
    return (
      <div className="space-y-1">
        <Progress value={poller.progressPercent} className="h-1.5" />
        <div className="flex items-center gap-2 text-xs text-muted-foreground">
          <span>{poller.progressMessage || "Starting..."}</span>
          {poller.totalSteps > 0 && (
            <span className="ml-auto tabular-nums">
              {poller.step}/{poller.totalSteps}
            </span>
          )}
        </div>
      </div>
    );
  }

  if (poller.status === "COMPLETED") {
    return (
      <div className="flex items-center gap-2">
        <div className="h-3 w-3 shrink-0 animate-spin rounded-full border-2 border-primary border-t-transparent" />
        <span className="text-xs text-muted-foreground">Loading results...</span>
      </div>
    );
  }

  return null;
}
